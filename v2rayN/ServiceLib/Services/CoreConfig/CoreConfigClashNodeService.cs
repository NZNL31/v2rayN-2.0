namespace ServiceLib.Services.CoreConfig;

/// <summary>
/// 用单个节点生成 mihomo (Clash.Meta) 内核的 YAML 配置。
/// 支持的协议见 Global.MihomoSupportConfigType；暂不生成自定义分流规则（全部走代理）。
/// 生成结果只使用 mihomo 原生字段，数字/布尔值不加引号，字符串统一单引号包裹。
/// </summary>
public class CoreConfigClashNodeService(CoreConfigContext context)
{
    private const string _tag = "CoreConfigClashNodeService";

    private readonly Config _config = context.AppConfig;
    private readonly ProfileItem _node = context.Node;

    private static readonly HashSet<string> _supportedNetworks =
    [
        nameof(ETransport.raw),
        "tcp",
        nameof(ETransport.ws),
        nameof(ETransport.grpc),
        nameof(ETransport.h2),
    ];

    #region public gen function

    public RetResult GenerateClientConfigContent()
    {
        var ret = new RetResult();
        try
        {
            if (_node == null || !_node.IsValid())
            {
                ret.Msg = ResUI.CheckServerSettings;
                return ret;
            }

            var proxyYaml = BuildProxyYaml(_node, out var error);
            if (proxyYaml == null)
            {
                ret.Msg = error;
                return ret;
            }

            ret.Msg = ResUI.InitialConfiguration;

            var sb = new StringBuilder();
            sb.AppendLine("# generated by v2rayN (mihomo core)");
            AppendInbound(sb, AppManager.Instance.GetLocalPort(EInboundProtocol.socks));
            AppendDns(sb);
            sb.AppendLine("proxies:");
            sb.Append(proxyYaml);
            sb.AppendLine("rules:");
            sb.AppendLine($"  - 'MATCH,{Global.ProxyTag}'");
            AppendTun(sb);

            ret.Msg = string.Format(ResUI.SuccessfulConfiguration, "");
            ret.Success = true;
            ret.Data = sb.ToString();
            return ret;
        }
        catch (Exception ex)
        {
            Logging.SaveLog(_tag, ex);
            ret.Msg = ResUI.FailedGenDefaultConfiguration;
            return ret;
        }
    }

    public RetResult GenerateClientSpeedtestConfig(int testPort)
    {
        var ret = new RetResult();
        try
        {
            var proxyYaml = BuildProxyYaml(_node, out var error);
            if (proxyYaml == null)
            {
                ret.Msg = error;
                return ret;
            }

            ret.Msg = ResUI.InitialConfiguration;

            var sb = new StringBuilder();
            sb.AppendLine("# generated by v2rayN (mihomo core, speedtest)");
            AppendInbound(sb, testPort, true);
            sb.AppendLine("proxies:");
            sb.Append(proxyYaml);
            sb.AppendLine("rules:");
            sb.AppendLine($"  - 'MATCH,{Global.ProxyTag}'");

            ret.Msg = string.Format(ResUI.SuccessfulConfiguration, "");
            ret.Success = true;
            ret.Data = sb.ToString();
            return ret;
        }
        catch (Exception ex)
        {
            Logging.SaveLog(_tag, ex);
            ret.Msg = ResUI.FailedGenDefaultConfiguration;
            return ret;
        }
    }

    #endregion public gen function

    #region inbound

    private void AppendInbound(StringBuilder sb, int listenPort, bool isSpeedtest = false)
    {
        var inbound = _config.Inbound.First();
        var allowLan = inbound.AllowLANConn && !isSpeedtest;

        sb.AppendLine($"mixed-port: {listenPort}");
        sb.AppendLine($"allow-lan: {B(allowLan)}");
        if (allowLan)
        {
            sb.AppendLine("bind-address: '*'");
        }
        sb.AppendLine("mode: 'rule'");
        sb.AppendLine($"log-level: {Q(GetLogLevel())}");
        sb.AppendLine("ipv6: true");

        if (isSpeedtest)
        {
            return;
        }

        // Clash API：状态栏实时速率、连接列表、延迟测试都走这个端口
        sb.AppendLine($"external-controller: {Q($"{Global.Loopback}:{AppManager.Instance.StatePort2}")}");

        if (inbound.User.IsNotEmpty() && inbound.Pass.IsNotEmpty())
        {
            sb.AppendLine("authentication:");
            sb.AppendLine($"  - {Q($"{inbound.User}:{inbound.Pass}")}");
        }

        if (!inbound.SecondLocalPortEnabled && !(inbound.AllowLANConn && inbound.NewPort4LAN))
        {
            return;
        }

        sb.AppendLine("listeners:");
        if (inbound.SecondLocalPortEnabled)
        {
            AppendListener(sb, nameof(EInboundProtocol.socks2), listenPort + (int)EInboundProtocol.socks2, Global.Loopback);
        }
        if (inbound.AllowLANConn && inbound.NewPort4LAN)
        {
            AppendListener(sb, nameof(EInboundProtocol.socks3), listenPort + (int)EInboundProtocol.socks3, "0.0.0.0");
        }
    }

    private static void AppendListener(StringBuilder sb, string name, int port, string listen)
    {
        sb.AppendLine($"  - name: {Q(name)}");
        sb.AppendLine("    type: 'mixed'");
        sb.AppendLine($"    port: {port}");
        sb.AppendLine($"    listen: {Q(listen)}");
    }

    private void AppendDns(StringBuilder sb)
    {
        if (!context.IsTunEnabled)
        {
            return;
        }
        sb.AppendLine("dns:");
        sb.AppendLine("  enable: true");
        sb.AppendLine("  enhanced-mode: 'fake-ip'");
        sb.AppendLine("  nameserver:");
        sb.AppendLine("    - '223.5.5.5'");
        sb.AppendLine("    - '119.29.29.29'");
    }

    private void AppendTun(StringBuilder sb)
    {
        if (!context.IsTunEnabled)
        {
            return;
        }

        var tun = _config.TunModeItem;
        var stack = tun.Stack.NullIfEmpty() ?? Global.TunStacks.First();
        var mtu = tun.Mtu > 0 ? tun.Mtu : Global.TunMtus.First();

        sb.AppendLine("tun:");
        sb.AppendLine("  enable: true");
        sb.AppendLine($"  stack: {Q(stack)}");
        sb.AppendLine("  auto-route: true");
        sb.AppendLine("  auto-detect-interface: true");
        sb.AppendLine($"  strict-route: {B(tun.StrictRoute)}");
        sb.AppendLine($"  mtu: {mtu}");
        sb.AppendLine("  dns-hijack:");
        sb.AppendLine("    - 'any:53'");
        sb.AppendLine("    - 'tcp://any:53'");

        if (tun.RouteExcludeAddress is not { Count: > 0 })
        {
            return;
        }
        sb.AppendLine("  route-exclude-address:");
        foreach (var address in tun.RouteExcludeAddress)
        {
            sb.AppendLine($"    - {Q(address)}");
        }
    }

    #endregion inbound

    #region proxy

    private string? BuildProxyYaml(ProfileItem node, out string error)
    {
        error = string.Empty;

        var extra = node.GetProtocolExtra();
        var transport = node.GetTransportExtra();
        var network = node.GetNetwork();
        var reality = node.StreamSecurity == Global.StreamSecurityReality;
        var useTls = reality || node.StreamSecurity == Global.StreamSecurity;
        var streamProtocol = node.ConfigType is EConfigType.VMess or EConfigType.VLESS or EConfigType.Trojan;

        var type = node.ConfigType switch
        {
            EConfigType.VMess => "vmess",
            EConfigType.VLESS => "vless",
            EConfigType.Trojan => "trojan",
            EConfigType.Shadowsocks => "ss",
            EConfigType.SOCKS => "socks5",
            EConfigType.HTTP => "http",
            EConfigType.Hysteria2 => "hysteria2",
            _ => null,
        };
        if (type is null)
        {
            error = string.Format(ResUI.MsgCoreNotSupportProtocol, nameof(ECoreType.mihomo), node.ConfigType);
            return null;
        }

        if (streamProtocol && !_supportedNetworks.Contains(network))
        {
            error = string.Format(ResUI.MsgCoreNotSupportNetwork, nameof(ECoreType.mihomo), network);
            return null;
        }

        var sb = new StringBuilder();
        sb.AppendLine($"  - name: {Q(Global.ProxyTag)}");
        sb.AppendLine($"    type: {Q(type)}");
        sb.AppendLine($"    server: {Q(node.Address)}");
        sb.AppendLine($"    port: {node.Port}");
        sb.AppendLine("    udp: true");

        switch (node.ConfigType)
        {
            case EConfigType.VMess:
                sb.AppendLine($"    uuid: {Q(node.Password)}");
                sb.AppendLine($"    alterId: {GetInt(extra.AlterId, 0)}");
                sb.AppendLine("    cipher: 'auto'");
                break;

            case EConfigType.VLESS:
                sb.AppendLine($"    uuid: {Q(node.Password)}");
                if (extra.Flow.IsNotEmpty())
                {
                    sb.AppendLine($"    flow: {Q(extra.Flow)}");
                }
                break;

            case EConfigType.Trojan:
                sb.AppendLine($"    password: {Q(node.Password)}");
                break;

            case EConfigType.Shadowsocks:
                sb.AppendLine($"    cipher: {Q(extra.SsMethod ?? string.Empty)}");
                sb.AppendLine($"    password: {Q(node.Password)}");
                break;

            case EConfigType.SOCKS:
            case EConfigType.HTTP:
                if (node.Username.IsNotEmpty())
                {
                    sb.AppendLine($"    username: {Q(node.Username)}");
                }
                if (node.Password.IsNotEmpty())
                {
                    sb.AppendLine($"    password: {Q(node.Password)}");
                }
                break;

            case EConfigType.Hysteria2:
                sb.AppendLine($"    password: {Q(node.Password)}");
                if (extra.UpMbps is > 0)
                {
                    sb.AppendLine($"    up: {Q($"{extra.UpMbps} Mbps")}");
                }
                if (extra.DownMbps is > 0)
                {
                    sb.AppendLine($"    down: {Q($"{extra.DownMbps} Mbps")}");
                }
                if (extra.SalamanderPass.IsNotEmpty())
                {
                    sb.AppendLine("    obfs: 'salamander'");
                    sb.AppendLine($"    obfs-password: {Q(extra.SalamanderPass)}");
                }
                break;
        }

        // hysteria2 本身就是 TLS，不需要 tls: true；socks/ss 也不支持
        if (node.ConfigType is not (EConfigType.Hysteria2 or EConfigType.Shadowsocks or EConfigType.SOCKS)
            && useTls)
        {
            sb.AppendLine("    tls: true");
        }

        if (node.ConfigType is not (EConfigType.Shadowsocks or EConfigType.SOCKS)
            && node.Sni.IsNotEmpty())
        {
            sb.AppendLine($"    sni: {Q(node.Sni)}");
        }

        if (node.GetAllowInsecure())
        {
            sb.AppendLine("    skip-cert-verify: true");
        }

        if (useTls)
        {
            AppendTlsOptions(sb, node, reality);
        }

        if (streamProtocol)
        {
            AppendTransport(sb, node, transport, network);
        }

        return sb.ToString();
    }

    private static void AppendTlsOptions(StringBuilder sb, ProfileItem node, bool reality)
    {
        var alpn = node.GetAlpn();
        if (alpn is { Count: > 0 })
        {
            sb.AppendLine("    alpn:");
            foreach (var item in alpn)
            {
                sb.AppendLine($"      - {Q(item)}");
            }
        }

        sb.AppendLine($"    client-fingerprint: {Q(node.Fingerprint.NullIfEmpty() ?? "chrome")}");

        if (!reality)
        {
            return;
        }
        sb.AppendLine("    reality-opts:");
        sb.AppendLine($"      public-key: {Q(node.PublicKey)}");
        sb.AppendLine($"      short-id: {Q(node.ShortId ?? string.Empty)}");
    }

    private static void AppendTransport(StringBuilder sb, ProfileItem node, TransportExtraItem transport, string network)
    {
        switch (network)
        {
            case nameof(ETransport.ws):
                sb.AppendLine("    network: 'ws'");
                sb.AppendLine("    ws-opts:");
                sb.AppendLine($"      path: {Q(transport.Path.NullIfEmpty() ?? "/")}");
                var host = transport.Host.NullIfEmpty() ?? node.Sni.NullIfEmpty();
                if (host.IsNotEmpty())
                {
                    sb.AppendLine("      headers:");
                    sb.AppendLine($"        Host: {Q(host)}");
                }
                break;

            case nameof(ETransport.grpc):
                sb.AppendLine("    network: 'grpc'");
                var grpcServiceName = transport.GrpcServiceName.NullIfEmpty() ?? transport.Path.NullIfEmpty();
                if (grpcServiceName.IsNotEmpty())
                {
                    sb.AppendLine("    grpc-opts:");
                    sb.AppendLine($"      grpc-service-name: {Q(grpcServiceName)}");
                }
                break;

            case nameof(ETransport.h2):
                sb.AppendLine("    network: 'h2'");
                sb.AppendLine("    h2-opts:");
                var h2Host = transport.Host.NullIfEmpty() ?? node.Sni.NullIfEmpty();
                if (h2Host.IsNotEmpty())
                {
                    sb.AppendLine("      host:");
                    foreach (var item in h2Host.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                    {
                        sb.AppendLine($"        - {Q(item)}");
                    }
                }
                sb.AppendLine($"      path: {Q(transport.Path.NullIfEmpty() ?? "/")}");
                break;

            default:
                // raw / tcp 是 mihomo 的默认传输方式，不需要输出
                break;
        }
    }

    #endregion proxy

    #region helpers

    private string GetLogLevel()
    {
        var level = _config.CoreBasicItem.Loglevel.NullIfEmpty() ?? "info";
        return level == "none" ? "silent" : level;
    }

    private static string Q(string? value)
    {
        return "'" + (value ?? string.Empty).Replace("'", "''") + "'";
    }

    private static string B(bool value)
    {
        return value ? "true" : "false";
    }

    private static int GetInt(string? value, int defaultValue)
    {
        return int.TryParse(value, out var result) ? result : defaultValue;
    }

    #endregion helpers
}
